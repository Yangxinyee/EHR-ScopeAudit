#!/usr/bin/env python3
"""LaTeX macros and tables from the panel analysis (plan §9.5). Loads no model; deterministic output (no
timestamps, sorted keys) so a rebuild is byte-identical. Every number in the generated files traces to
panel.json, which traces to the saved predictions.

Usage: generate_tables.py --panel-b experiments/scopebench_analysis/tierB/panel/panel.json
       [--panel-a ...] [--panel-c ...] --out paper/generated_scopebench
Writes: macros.tex, table_main.tex (Table 2), table_tests.tex (Table 5), table_factor.tex (Table 3),
table_coverage.tex (Table 4), table_stages.tex (Table 6), table_cost.tex (Table 8), table_models.tex (S1),
table_strata.tex (S2), table_abstain.tex (S3), table_policy.tex (S4), table_errors.tex, README.md.
Rows whose configuration was not run are printed as "---" (never invented).
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROW_LABEL = {"prompt_only": "Prompt-only", "late_filter": "Late filtering", "wrong_basis": "Wrong-basis scope", "scope_aware": "Scope-aware retrieval",
             "audit": "$+$ evidence audit", "full": "$+$ skill grounding", "token_matched": "Token-matched control", "high_compute": "High-compute control",
             "retry_generic": "$+$ equal-call generic retry", "feedback_schema_only": "$+$ schema feedback and retry", "skill_payload_only": "$+$ skill payload only",
             "skill_verify_no_replace": "$+$ payload, verify, no replacement", "skill_replace_no_payload": "$+$ replacement, no payload",
             "citation_validator": "Output citation validator", "reranker": "Evidence reranker", "temporal_sql_view": "Temporal SQL view", "abac_pdp": "Generic ABAC policy engine"}
CORE = ["prompt_only", "late_filter", "wrong_basis", "scope_aware", "audit", "full", "token_matched", "high_compute"]
TIER_MACRO = {"B": r"\tierB{}", "A": r"\tierA{}", "C": r"\tierC{}"}
CKPT_LABEL = {"qwen3_4b": "Qwen3-4B", "phi4_14b": "Phi-4", "gemma3_27b": "Gemma-3-27B", "medgemma_27b": "MedGemma-27B", "qwen3_32b": "Qwen3-32B",
              "qwen3_30b": "Qwen3-30B-A3B", "llama33_70b": "Llama-3.3-70B", "claude_opus": "Claude Opus"}
CKPT_ORDER = ["qwen3_4b", "phi4_14b", "gemma3_27b", "medgemma_27b", "qwen3_32b", "qwen3_30b", "llama33_70b", "claude_opus"]
TT_LABEL = {"lab_trend_k3": "Evidence retrieval", "outcome_lookup_v1": "Outcome abstraction", "cohort_v1": "Cohort abstraction", "claim_v1": "Claim verification",
            "reconstruct_v1": "Report reconstruction", "summarize_exams_v1": "Evidence-grounded summarization"}
SCOPE_LABEL = {"pre": "Pre-index", "at": "At-index", "post": "Post-index", "full": "Full-chart"}
HYP_LABEL = {"H1_scope_vs_prompt": "Prompt-only $\\to$ scope-aware (Ev.C)", "H2_audit_vs_scope": "Scope-aware $\\to +$audit (Ev.C)",
             "H3_full_vs_audit": "$+$audit $\\to +$skill (Ev.C)", "H4_scope_vs_wrongbasis_citation": "Wrong-basis $\\to$ scope-aware (C-L)"}


def f1(x) -> str:
    return "---" if x is None else f"{x:.1f}"


def signed(x) -> str:
    return "---" if x is None else f"{x:+.1f}"


def pfmt(p) -> str:
    if p is None:
        return "---"
    return "$<$.001" if p < 0.001 else f"{p:.3f}".lstrip("0")


def macro_name(*parts: str) -> str:
    s = "".join(w.capitalize() for part in parts for w in re.split(r"[^A-Za-z0-9]+", part) if w)
    return "sb" + re.sub(r"[0-9]", lambda m: "ZOTTFFSSEN"[int(m.group())], s)


class Out:
    def __init__(self, out: Path):
        self.out = out; self.macros: dict[str, str] = {}; self.files: dict[str, str] = {}

    def macro(self, name: str, value: str) -> None:
        self.macros[name] = value

    def table(self, name: str, body: str) -> None:
        self.files[name] = body

    def write(self) -> None:
        self.out.mkdir(parents=True, exist_ok=True)
        lines = ["% generated by scripts/scopebench/generate_tables.py from panel.json — do not edit"]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.macros.items())]
        (self.out / "macros.tex").write_text("\n".join(lines) + "\n")
        for name, body in self.files.items():
            (self.out / name).write_text("% generated by scripts/scopebench/generate_tables.py — do not edit\n" + body)


def endpoint_rows(o: Out, panels: dict[str, dict], tier: str, configs: list[str], prefix: str) -> list[str]:
    rows = []
    P = panels.get(tier)
    for c in configs:
        avg = (P or {}).get("checkpoint_average", {}).get(c)
        vals = [avg.get(ep) if avg else None for ep in ("answer_correct", "completeness", "access_legal", "citation_legal", "auditable")]
        bold = c == "full"
        cells = [f"\\textbf{{{f1(v)}}}" if bold and v is not None else f1(v) for v in vals]
        rows.append(f"& {ROW_LABEL.get(c, c):24s} & " + " & ".join(cells) + " \\\\")
        for ep, v in zip(("Ans", "EvC", "AL", "CL", "Aud"), vals):
            if v is not None:
                o.macro(macro_name(prefix, tier, c, ep), f1(v))
        if avg:
            o.macro(macro_name(prefix, tier, c, "abst"), f1(avg.get("abstained")))
            o.macro(macro_name(prefix, tier, c, "nckpt"), str(avg.get("n_checkpoints")))
    return rows


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--panel-b", type=Path, required=True)
    p.add_argument("--panel-a", type=Path, default=None)
    p.add_argument("--panel-c", type=Path, default=None)
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args()
    panels = {"B": json.loads(args.panel_b.read_text())}
    if args.panel_a:
        panels["A"] = json.loads(args.panel_a.read_text())
    if args.panel_c:
        panels["C"] = json.loads(args.panel_c.read_text())
    o = Out(args.out)
    B = panels["B"]

    # Table 2 — endpoints averaged over checkpoints, per tier
    body = ["\\begin{tabular}{@{}llrrrrr@{}}", "\\toprule", "Tier & Configuration & Ans. & Ev.C & A-L & C-L & Aud. \\\\", "\\midrule"]
    for tier in [t for t in ("B", "A", "C") if t in panels]:
        body.append(f"\\multirow{{8}}{{*}}{{{TIER_MACRO[tier]}}}")
        body += endpoint_rows(o, panels, tier, CORE, "main")
        body.append("\\midrule")
    body[-1] = "\\bottomrule"; body.append("\\end{tabular}")
    o.table("table_main.tex", "\n".join(body) + "\n")
    o.macro("sbTierBCheckpoints", str(len(B["checkpoints"])))
    o.macro("sbTierBCheckpointList", ", ".join(CKPT_LABEL.get(t, t) for t in sorted(B["checkpoints"], key=lambda t: CKPT_ORDER.index(t) if t in CKPT_ORDER else 99)))

    # Table 5 — pooled prespecified contrasts
    body = ["\\begin{tabular}{@{}lrrr@{}}", "\\toprule", "Prespecified comparison (\\tierB{}) & $\\Delta$ & 95\\% CI & Holm $p$ \\\\", "\\midrule"]
    for name in ("H1_scope_vs_prompt", "H2_audit_vs_scope", "H3_full_vs_audit", "H4_scope_vs_wrongbasis_citation"):
        h = B["hypotheses"]["pooled"].get(name)
        if h:
            body.append(f"{HYP_LABEL[name]} & ${signed(h['delta_pct'])}$ & {f1(h['ci_low_pct'])}--{f1(h['ci_high_pct'])} & {pfmt(h.get('p_holm'))} \\\\")
            o.macro(macro_name("tests", name, "delta"), signed(h["delta_pct"])); o.macro(macro_name("tests", name, "lo"), f1(h["ci_low_pct"]))
            o.macro(macro_name("tests", name, "hi"), f1(h["ci_high_pct"])); o.macro(macro_name("tests", name, "p"), pfmt(h.get("p_holm")))
        else:
            body.append(f"{HYP_LABEL[name]} & --- & --- & --- \\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_tests.tex", "\n".join(body) + "\n")

    # Table 3 — attribution arms
    body = ["\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule", "\\tierB{} attribution arm & Ans. & Ev.C & A-L & C-L & Aud. & Answer changed / trace-only \\\\", "\\midrule"]
    for c in ("scope_aware", "retry_generic", "feedback_schema_only", "audit"):
        body.append(attrib_row(o, B, c, "Audit baseline" if c == "audit" and False else None))
    body.append("\\midrule")
    for c in ("audit", "skill_payload_only", "skill_verify_no_replace", "skill_replace_no_payload", "full"):
        body.append(attrib_row(o, B, c, {"audit": "Audit baseline", "full": "Full system"}.get(c)))
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_factor.tex", "\n".join(body) + "\n")

    # Table 4 — coverage (Tier-B by task type; other tiers when present)
    cov = B["coverage"]
    body = ["\\begin{tabular}{@{}lrrr@{}}", "\\toprule", "Task type & \\tierB{} & \\tierA{} & \\tierC{} \\\\", "\\midrule"]
    for tt in sorted(cov["by_task_type"], key=lambda k: list(TT_LABEL).index(k) if k in TT_LABEL else 99):
        a = panels.get("A", {}).get("coverage", {}).get("by_task_type", {}).get(tt); c_ = panels.get("C", {}).get("coverage", {}).get("by_task_type", {}).get(tt)
        body.append(f"{TT_LABEL.get(tt, tt)} & {f1(cov['by_task_type'][tt])} & {f1(a)} & {f1(c_)} \\\\")
    body.append("\\midrule")
    body.append(f"All tasks & {f1(cov['all_tasks_pct'])} & {f1(panels.get('A', {}).get('coverage', {}).get('all_tasks_pct'))} & {f1(panels.get('C', {}).get('coverage', {}).get('all_tasks_pct'))} \\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_coverage.tex", "\n".join(body) + "\n")
    o.macro("sbCoverageTierBAll", f1(cov["all_tasks_pct"])); o.macro("sbUncoveredTierBAll", f1(100 - cov["all_tasks_pct"]))

    # Table 6 — covered-operation stages
    body = ["\\begin{tabular}{@{}lrrrr@{}}", "\\toprule", "Tier & Initial & $+$Repair & Replaced & Final \\\\", "\\midrule"]
    for tier in [t for t in ("B", "A", "C") if t in panels]:
        s = panels[tier].get("stages", {}).get("mean") or {}
        body.append(f"{TIER_MACRO[tier]} & {f1(s.get('initial_valid_pct'))} & {f1(s.get('after_repair_valid_pct'))} & {f1(s.get('replaced_pct'))} & {f1(s.get('final_valid_pct'))} \\\\")
        for k in ("initial_valid_pct", "after_repair_valid_pct", "replaced_pct", "final_valid_pct", "initial_correct_pct", "final_correct_pct", "wrong_corrected_only_by_replacement_pct_of_all_tasks", "already_correct_replaced_pct_of_covered"):
            if s.get(k) is not None:
                o.macro(macro_name("stages", tier, k), f1(s[k]))
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_stages.tex", "\n".join(body) + "\n")

    # Table 8 — cost relative to prompt-only (checkpoint means)
    body = ["\\begin{tabular}{@{}lrrrr@{}}", "\\toprule", "Configuration & Tokens & Calls & Latency & GPU-hours \\\\", "\\midrule"]
    for c in ("prompt_only", "scope_aware", "audit", "full", "token_matched", "high_compute"):
        m = B.get("cost", {}).get(c, {}).get("mean")
        if m:
            body.append(f"{ROW_LABEL[c]:24s} & {m['tokens_ratio']:.2f} & {m['calls']:.1f} & {m['latency_ratio']:.2f} & {m['wall_hours_ratio']:.2f} \\\\" if m.get("wall_hours_ratio") is not None
                        else f"{ROW_LABEL[c]:24s} & {m['tokens_ratio']:.2f} & {m['calls']:.1f} & {m['latency_ratio']:.2f} & --- \\\\")
            o.macro(macro_name("cost", c, "tokens"), f"{m['tokens_ratio']:.2f}"); o.macro(macro_name("cost", c, "latency"), f"{m['latency_ratio']:.2f}")
        else:
            body.append(f"{ROW_LABEL[c]:24s} & --- & --- & --- & --- \\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_cost.tex", "\n".join(body) + "\n")

    # S1 — checkpoint-level values (Figure 2)
    body = ["\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule", "Checkpoint & \\multicolumn{2}{c}{Prompt-only} & \\multicolumn{2}{c}{Full} & $\\Delta$ Ans. & $\\Delta$ Ev.C \\\\",
            " & Ans. & Ev.C & Ans. & Ev.C & & \\\\", "\\midrule"]
    ms = B.get("models", {})
    for t in sorted(ms, key=lambda t: CKPT_ORDER.index(t) if t in CKPT_ORDER else 99):
        m = ms[t]
        body.append(f"{CKPT_LABEL.get(t, t)} & {f1(m['prompt_only']['answer_correct']['mean'])} & {f1(m['prompt_only']['completeness']['mean'])} & {f1(m['full']['answer_correct']['mean'])} & {f1(m['full']['completeness']['mean'])} & {signed(m['delta_answer_correct'])} & {signed(m['delta_completeness'])} \\\\")
        o.macro(macro_name("model", t, "dAns"), signed(m["delta_answer_correct"])); o.macro(macro_name("model", t, "dEvC"), signed(m["delta_completeness"]))
    if ms:
        body.append("\\midrule")
        body.append(f"Mean & {f1(sum(m['prompt_only']['answer_correct']['mean'] for m in ms.values()) / len(ms))} & {f1(sum(m['prompt_only']['completeness']['mean'] for m in ms.values()) / len(ms))} & "
                    f"{f1(sum(m['full']['answer_correct']['mean'] for m in ms.values()) / len(ms))} & {f1(sum(m['full']['completeness']['mean'] for m in ms.values()) / len(ms))} & "
                    f"{signed(sum(m['delta_answer_correct'] for m in ms.values()) / len(ms))} & {signed(sum(m['delta_completeness'] for m in ms.values()) / len(ms))} \\\\")
        pa = [m["prompt_only"]["answer_correct"]["mean"] for m in ms.values()]; pc = [m["prompt_only"]["completeness"]["mean"] for m in ms.values()]
        o.macro("sbPromptOnlyAnsBand", f"{min(pa):.1f}--{max(pa):.1f}"); o.macro("sbPromptOnlyEvCBand", f"{min(pc):.1f}--{max(pc):.1f}")
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_models.tex", "\n".join(body) + "\n")

    # S2 — strata deltas (full − prompt-only)
    st = B.get("strata", {})
    body = ["\\begin{tabular}{@{}llrrrr@{}}", "\\toprule", "Stratum & Level & $\\Delta$ Ans. & $\\Delta$ Ev.C & $\\Delta$ A-L & $\\Delta$ Aud. \\\\", "\\midrule"]
    tts = [k for k in st if k.startswith("task_type=")]
    body.append(f"\\multirow{{{len(tts)}}}{{*}}{{Task}}")
    for k in sorted(tts, key=lambda k: list(TT_LABEL).index(k.split("=", 1)[1]) if k.split("=", 1)[1] in TT_LABEL else 99):
        body.append(strata_row(o, st, k, TT_LABEL.get(k.split("=", 1)[1], k)))
    body.append("\\midrule")
    scs = [k for k in st if k.startswith("scope=")]
    body.append(f"\\multirow{{{len(scs)}}}{{*}}{{Scope}}")
    for k in sorted(scs, key=lambda k: list(SCOPE_LABEL).index(k.split("=", 1)[1]) if k.split("=", 1)[1] in SCOPE_LABEL else 99):
        body.append(strata_row(o, st, k, SCOPE_LABEL.get(k.split("=", 1)[1], k)))
    lk = [k for k in st if k.startswith("leakage=")]
    if lk:
        body.append("\\midrule"); body.append(f"\\multirow{{{len(lk)}}}{{*}}{{Leakage stratum}}")
        for k in sorted(lk):
            body.append(strata_row(o, st, k, "Leakage-flagged" if k.endswith("True") else "Not flagged"))
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_strata.tex", "\n".join(body) + "\n")

    # S3 — abstention per tier
    body = ["\\begin{tabular}{@{}lrrr@{}}", "\\toprule", "Configuration & \\tierB{} & \\tierA{} & \\tierC{} \\\\", "\\midrule"]
    for c in CORE:
        vals = [panels.get(t, {}).get("checkpoint_average", {}).get(c, {}).get("abstained") for t in ("B", "A", "C")]
        body.append(f"{ROW_LABEL[c]:24s} & " + " & ".join(f1(v) for v in vals) + " \\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_abstain.tex", "\n".join(body) + "\n")

    # S4 — baselines (Tier-B rows; Tier-C rows when present)
    body = ["\\begin{tabular}{@{}llrrrrr@{}}", "\\toprule", "Tier & Baseline & Ans. & Ev.C & A-L & C-L & Aud. \\\\", "\\midrule", "\\multirow{6}{*}{\\tierB{}}"]
    body += endpoint_rows(o, panels, "B", ["citation_validator", "reranker", "temporal_sql_view", "abac_pdp", "scope_aware", "full"], "policy")
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_policy.tex", "\n".join(body) + "\n")

    # Error taxonomy — raw counts per configuration (pooled over checkpoints)
    tax = B.get("error_taxonomy", {}).get("by_configuration", {})
    cats = ["omission", "out_of_scope_citation", "operation_error", "schema", "none"]
    body = ["\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule", "Configuration & Omission & Out-of-scope citation & Operation error & Schema & Correct \\& valid & $n$ \\\\", "\\midrule"]
    for c in CORE + ["retry_generic", "feedback_schema_only", "skill_payload_only", "skill_verify_no_replace", "skill_replace_no_payload", "citation_validator", "reranker", "temporal_sql_view", "abac_pdp"]:
        if c in tax:
            pc = tax[c]["pooled_counts"]
            body.append(f"{ROW_LABEL.get(c, c):24s} & " + " & ".join(str(pc.get(k, 0)) for k in cats) + f" & {tax[c]['n']} \\\\")
    body += ["\\bottomrule", "\\end{tabular}"]
    o.table("table_errors.tex", "\n".join(body) + "\n")

    # association sentences
    A = B.get("associations", {})
    for key, v in A.get("checkpoint_level", {}).items():
        c, rest = key.split("|"); ep = rest.split("~")[1]
        o.macro(macro_name("assoc", c, ep, "r"), f"{v['r']:.2f}".replace("0.", ".")); o.macro(macro_name("assoc", c, ep, "lo"), f"{v['ci_low']:.2f}".replace("0.", "."))
        o.macro(macro_name("assoc", c, ep, "hi"), f"{v['ci_high']:.2f}".replace("0.", "."))
    ml = A.get("multilevel") or {}
    for name, key in (("completeness10", "completenessTen"), ("citation_legal", "citationLegal")):
        fe = (ml.get("fixed_effects") or {}).get(name)
        if fe:
            o.macro(macro_name("ml", key, "or"), f"{fe['odds_ratio']:.2f}"); o.macro(macro_name("ml", key, "lo"), f"{fe['ci_low']:.2f}"); o.macro(macro_name("ml", key, "hi"), f"{fe['ci_high']:.2f}")
    if ml.get("method"):
        o.macro("sbMultilevelMethod", ml["method"].replace("_", "\\_")); o.macro("sbMultilevelRows", str(ml.get("n_rows_fit")))
    for k, v in (A.get("conditional_mi_bits") or {}).items():
        o.macro(macro_name("cmi", "completeness" if "completeness" in k else "citation"), f"{v:.3f}".replace("0.", "."))
    sp = B.get("params_vs_completeness_spearman")
    if sp and "rho" in sp:
        o.macro("sbParamsSpearmanRho", f"{sp['rho']:.2f}"); o.macro("sbParamsSpearmanP", pfmt(sp["p"]))
    mx = B.get("matrix", {})
    if mx.get("min_completeness_gain"):
        k, v = mx["min_completeness_gain"]; t, tt, sc = k.split("|")
        o.macro("sbMatrixMinGain", f1(v["delta_completeness_pct"])); o.macro("sbMatrixMinCell", f"{CKPT_LABEL.get(t, t)}, {SCOPE_LABEL.get(sc, sc).lower()} {TT_LABEL.get(tt, tt).lower()}")
        k, v = mx["max_completeness_gain"]; t, tt, sc = k.split("|")
        o.macro("sbMatrixMaxGain", f1(v["delta_completeness_pct"])); o.macro("sbMatrixMaxCell", f"{CKPT_LABEL.get(t, t)}, {SCOPE_LABEL.get(sc, sc).lower()} {TT_LABEL.get(tt, tt).lower()}")
        o.macro("sbMatrixNonpositiveCells", str(len(mx.get("cells_with_nonpositive_completeness_gain", []))))
    div = B.get("access_citation_divergence", {})
    for c in ("prompt_only", "high_compute", "scope_aware"):
        if c in div and div[c]:
            o.macro(macro_name("divergence", c), f1(sum(v["legal_citations_after_illegal_exposure_pct"] for v in div[c].values()) / len(div[c])))
    o.write()
    readme = ["# Generated ScopeBench tables", "", f"Source: `{args.panel_b}`" + (f", `{args.panel_a}`" if args.panel_a else "") + (f", `{args.panel_c}`" if args.panel_c else ""),
              f"Checkpoints (Tier-B): {', '.join(B['checkpoints'])}", f"Configurations (Tier-B): {', '.join(B['configurations'])}", "",
              "Files: " + ", ".join(sorted(o.files) + ["macros.tex"]), "", "`---` marks a configuration or tier that has not been run. Regenerate with `scripts/scopebench/rebuild_all.sh`."]
    (args.out / "README.md").write_text("\n".join(readme) + "\n")
    print(f"wrote {len(o.files) + 2} files with {len(o.macros)} macros to {args.out}")


def attrib_row(o: Out, B: dict, c: str, label: str | None) -> str:
    avg = B.get("checkpoint_average", {}).get(c); at = B.get("attribution", {}).get(c, {}).get("mean")
    vals = [avg.get(ep) if avg else None for ep in ("answer_correct", "completeness", "access_legal", "citation_legal", "auditable")]
    tail = "n/a" if c == "scope_aware" or (c == "audit" and label) else (f"{f1(at['answer_changed_pct'])} / {f1(at['trace_only_pct'])}" if at else "---")
    if at:
        o.macro(macro_name("attrib", c, "changed"), f1(at["answer_changed_pct"])); o.macro(macro_name("attrib", c, "traceonly"), f1(at["trace_only_pct"]))
    return f"{label or ROW_LABEL.get(c, c)} & " + " & ".join(f1(v) for v in vals) + f" & {tail} \\\\"


def strata_row(o: Out, st: dict, key: str, label: str) -> str:
    v = st[key]
    for ep, short in (("answer_correct", "dAns"), ("completeness", "dEvC"), ("access_legal", "dAL"), ("auditable", "dAud")):
        o.macro(macro_name("strata", key, short), signed(v[ep]["delta_pct"]))
    return f"& {label} & {signed(v['answer_correct']['delta_pct'])} & {signed(v['completeness']['delta_pct'])} & {signed(v['access_legal']['delta_pct'])} & {signed(v['auditable']['delta_pct'])} \\\\"


if __name__ == "__main__":
    main()
