#!/usr/bin/env python3
"""Generate manuscript table rows directly from frozen analysis artifacts.

Every number emitted here is read from a saved CSV or JSONL artifact. The script
never loads a model and never recomputes a score from raw generations.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


# Ordered checkpoint panel. The order is by parameter count and is fixed before
# reading any result file.
PANEL: tuple[tuple[str, str], ...] = (
    ("Qwen__Qwen3-4B-Instruct-2507", "Qwen3-4B"),
    ("microsoft__phi-4", "Phi-4-14B"),
    ("google__gemma-3-27b-it", "Gemma-3-27B"),
    ("google__medgemma-27b-text-it", "MedGemma-27B"),
    ("Qwen__Qwen3-30B-A3B-Instruct-2507", "Qwen3-30B"),
)
MODEL_LABELS = dict(PANEL)
PANEL_ORDER = [label for _, label in PANEL]

# Macro-safe alphabetic aliases for LaTeX \newcommand names.
MACRO_ALIAS = {
    "Qwen3-4B": "QwenFour",
    "Phi-4-14B": "Phi",
    "Gemma-3-27B": "Gemma",
    "MedGemma-27B": "MedGemma",
    "Qwen3-30B": "QwenThirty",
}

LAB_ALL_SIX = "prompt_only_all6"
MED_ALL_SIX = "prompt_all6"

LAB_SYSTEM_ORDER = (
    ("unscoped", "Unscoped top-$3$"),
    ("late_no_refill", "Late-no-refill"),
    ("wrong_time_scope_first", "Wrong-time scope"),
    (LAB_ALL_SIX, "All-six"),
    ("scope_first", "Scope-first"),
    ("guard_refill", "Guard-refill"),
    ("clinehr_os", "\\system{}"),
)
MED_SYSTEM_ORDER = (
    ("unscoped", "Unscoped top-$3$"),
    ("late_no_refill", "Late-no-refill"),
    (MED_ALL_SIX, "All-six"),
    ("scope_first", "Scope-first"),
    ("guard_refill", "Guard-refill"),
    ("clinehr_os", "\\system{}"),
)

HEADER = "% Generated by scripts/generate_submission_tables.py; do not edit."


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def pct(value: str | float) -> str:
    return f"{100.0 * float(value):.2f}"


def signed_pct(value: float) -> str:
    formatted = f"{100.0 * value:.2f}"
    return f"+{formatted}" if value >= 0 else formatted


def tex_p(value: str | float) -> str:
    number = float(value)
    if number < 0.001:
        exponent = 0
        mantissa = number
        while mantissa and mantissa < 1:
            mantissa *= 10
            exponent -= 1
        return f"{mantissa:.2f}\\times10^{{{exponent}}}"
    return f"{number:.4f}".rstrip("0").rstrip(".")


def known_models(rows: list[dict[str, str]]) -> None:
    unknown = {row["model"] for row in rows} - set(MODEL_LABELS)
    if unknown:
        raise ValueError(f"Result files contain unlabelled checkpoints: {sorted(unknown)}")


def all_rows(path: Path) -> dict[tuple[str, str], dict[str, str]]:
    rows = [row for row in read_csv(path) if row["stratum"] == "all"]
    known_models(rows)
    return {(MODEL_LABELS[row["model"]], row["system"]): row for row in rows}


def keyed_rows(path: Path) -> dict[tuple[str, str], dict[str, str]]:
    rows = read_csv(path)
    known_models(rows)
    return {(MODEL_LABELS[row["model"]], row["system"]): row for row in rows}


def comparison_rows(path: Path) -> dict[tuple[str, str, str], dict[str, str]]:
    rows = read_csv(path)
    known_models(rows)
    return {
        (MODEL_LABELS[row["model"]], row["comparison_system"], row["baseline_system"]): row
        for row in rows
    }


def present_models(rows: dict) -> list[str]:
    """Panel order, restricted to checkpoints actually present in the artifacts."""
    available = {key[0] for key in rows}
    return [label for label in PANEL_ORDER if label in available]


def lab_stages(run_dir: Path) -> dict[str, float]:
    """Stage accounting for the full system, read from saved trajectories.

    A full-system task is valid after repair exactly when the verifier did not
    fall back, because the verifier checks every field and the aggregation.
    """
    records = [
        json.loads(line)
        for line in (run_dir / "predictions.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    full = [record for record in records if record["system"] == "clinehr_os"]
    if len(full) != 128:
        raise ValueError(f"Expected 128 full-system LabTrend records in {run_dir}")
    total = len(full)
    fallback = sum(bool(row.get("guard_deterministic_fallback")) for row in full) / total
    return {
        "initial_joint_valid": sum(not row.get("initial_guard_errors") for row in full) / total,
        "post_repair_joint_valid": 1.0 - fallback,
        "final_joint_valid": 1.0,
        "repair_rate": sum(bool(row.get("guard_repaired")) for row in full) / total,
        "deterministic_fallback_rate": fallback,
    }


def discover_runs(root: Path, pattern: str) -> dict[str, Path]:
    """Map checkpoint label to a frozen run directory matching the pattern."""
    runs: dict[str, Path] = {}
    for run_dir in sorted(root.glob(pattern)):
        metadata_path = run_dir / "metadata.json"
        if not metadata_path.exists():
            continue
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        name = Path(metadata["model_path"]).name
        if name in MODEL_LABELS:
            runs[MODEL_LABELS[name]] = run_dir
    return runs


def discover_lab_runs(root: Path) -> dict[str, Path]:
    """Map checkpoint label to its frozen LabTrend six-system run directory."""
    return discover_runs(root, "scopepair_fhir_test_*_frozen")


def truncation_rate(run_dir: Path, budget: int = 384) -> float:
    """Share of generations that ran into the shared token budget.

    Reported because the budget is deliberately shared across checkpoints rather
    than tuned per model, so a checkpoint that writes more verbosely can be
    penalized by it.
    """
    records = [
        json.loads(line)
        for line in (run_dir / "predictions.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    # A repaired task records the summed tokens of two generations, so it cannot
    # be compared against a single-generation budget.
    single = [record for record in records if not record.get("guard_repaired")]
    if not single:
        return 0.0
    return sum(
        int(record.get("generated_tokens", 0)) >= budget for record in single
    ) / len(single)


def table(columns: str, header: str, body: list[str]) -> list[str]:
    return [
        HEADER,
        f"\\begin{{tabular}}{{{columns}}}",
        "\\toprule",
        header,
        "\\midrule",
        *body,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--lab-analysis", type=Path,
        default=Path("experiments/scopepair_fhir_analysis_with_all6"),
    )
    parser.add_argument(
        "--lab-cases", type=Path,
        default=Path("experiments/scopepair_fhir_case_with_all6"),
    )
    parser.add_argument(
        "--experiments-root", type=Path, default=Path("experiments"),
    )
    parser.add_argument(
        "--med-analysis", type=Path,
        default=Path("experiments/scopepair_medadmin_test_analysis_frozen"),
    )
    parser.add_argument("--output-dir", type=Path, default=Path("paper/generated"))
    args = parser.parse_args()

    lab = all_rows(args.lab_analysis / "summary.csv")
    lab_cases = keyed_rows(args.lab_cases / "case_summary.csv")
    lab_comparisons = comparison_rows(args.lab_cases / "case_paired_comparisons.csv")
    med = all_rows(args.med_analysis / "summary.csv")
    med_cases = keyed_rows(args.med_analysis / "case_summary.csv")
    med_comparisons = comparison_rows(args.med_analysis / "case_paired_comparisons.csv")
    med_stage_rows = read_csv(args.med_analysis / "stage_summary.csv")
    known_models(med_stage_rows)
    med_stages = {MODEL_LABELS[row["model"]]: row for row in med_stage_rows}

    models = present_models(lab)
    if present_models(med) != models:
        raise ValueError(
            "LabTrend and MedDose analyses cover different checkpoints: "
            f"{models} vs {present_models(med)}"
        )
    lab_runs = discover_lab_runs(args.experiments_root)
    missing = [model for model in models if model not in lab_runs]
    if missing:
        raise ValueError(f"No frozen LabTrend run directory found for: {missing}")
    lab_stage_values = {model: lab_stages(lab_runs[model]) for model in models}
    med_runs = discover_runs(args.experiments_root, "scopepair_medadmin_test_*_frozen")
    truncation = {
        "Lab": {model: truncation_rate(lab_runs[model]) for model in models},
        "Med": {
            model: truncation_rate(med_runs[model])
            for model in models
            if model in med_runs
        },
    }

    # Case-level field names differ between the two analyzers.
    lab_case_field = "both_tasks_joint_valid"
    med_case_field = "both_task_case_success"

    families = (
        ("LabTrend", lab, lab_cases, lab_comparisons, LAB_ALL_SIX, lab_case_field),
        ("MedDose", med, med_cases, med_comparisons, MED_ALL_SIX, med_case_field),
    )

    # --- Table: task-level joint validity, both families side by side -------
    main_body = []
    for model in models:
        cells = []
        for _, rows, _, _, all_six, _ in families:
            for system in (all_six, "scope_first", "guard_refill"):
                cells.append(pct(rows[(model, system)]["joint_valid"]))
            cells.append(f"\\textbf{{{pct(rows[(model, 'clinehr_os')]['joint_valid'])}}}")
        main_body.append(f"{model} & " + " & ".join(cells) + " \\\\")
    main_lines = [
        HEADER,
        "\\begin{tabular}{l rrrr rrrr}",
        "\\toprule",
        " & \\multicolumn{4}{c}{LabTrend (availability time)}"
        " & \\multicolumn{4}{c}{MedDose (occurrence time)} \\\\",
        "\\cmidrule(lr){2-5} \\cmidrule(lr){6-9}",
        "Checkpoint & All-six & Scope & Guard & Full"
        " & All-six & Scope & Guard & Full \\\\",
        "\\midrule",
        *main_body,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ]

    # --- Table: independent-case both-task success --------------------------
    case_body = []
    for index, (family, _, cases, comparisons, all_six, field) in enumerate(families):
        for position, model in enumerate(models):
            all_six_value = float(cases[(model, all_six)][field])
            scope = float(cases[(model, "scope_first")][field])
            full = float(cases[(model, "clinehr_os")][field])
            p_value = comparisons[(model, "clinehr_os", "scope_first")][
                "holm_adjusted_case_p"
            ]
            prefix = (
                f"\\multirow{{{len(models)}}}{{*}}{{{family}}}" if position == 0 else ""
            )
            case_body.append(
                f"{prefix} & {model} & {pct(all_six_value)} & {pct(scope)} & "
                f"\\textbf{{{pct(full)}}} & {signed_pct(full - scope)} & "
                f"${tex_p(p_value)}$ \\\\"
            )
        if index == 0:
            case_body.append("\\midrule")
    case_lines = table(
        "ll rrrrr",
        "Family & Checkpoint & All-six & Scope-first & \\system{} & "
        "$\\Delta$ Full--Scope & Holm $p$ \\\\",
        case_body,
    )

    # --- Table: task-level and case-level in one full-width float -----------
    # The main paper carries this instead of the two tables above, which remain
    # available for the supplement and for the earlier two-float layout.
    combined_body: list[str] = []
    for index, (family, rows, cases, comparisons, all_six, field) in enumerate(families):
        for position, model in enumerate(models):
            task_cells = [
                pct(rows[(model, system)]["joint_valid"])
                for system in (all_six, "scope_first", "guard_refill")
            ]
            task_full = pct(rows[(model, "clinehr_os")]["joint_valid"])
            case_cells = [
                pct(cases[(model, system)][field])
                for system in (all_six, "scope_first")
            ]
            case_full = pct(cases[(model, "clinehr_os")][field])
            p_value = comparisons[(model, "clinehr_os", "scope_first")][
                "holm_adjusted_case_p"
            ]
            prefix = (
                f"\\multirow{{{len(models)}}}{{*}}{{{family}}}" if position == 0 else ""
            )
            combined_body.append(
                f"{prefix} & {model} & " + " & ".join(task_cells)
                + f" & \\textbf{{{task_full}}} & " + " & ".join(case_cells)
                + f" & \\textbf{{{case_full}}} & ${tex_p(p_value)}$ \\\\"
            )
        if index == 0:
            combined_body.append("\\midrule")
    combined_lines = [
        HEADER,
        "\\begin{tabular}{ll rrrr rrr r}",
        "\\toprule",
        " & & \\multicolumn{4}{c}{Task-level joint validity}"
        " & \\multicolumn{3}{c}{Independent-case success} & \\\\",
        "\\cmidrule(lr){3-6} \\cmidrule(lr){7-9}",
        "Family & Checkpoint & All-six & Scope & Guard & Full"
        " & All-six & Scope & Full & Holm $p$ \\\\",
        "\\midrule",
        *combined_body,
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ]

    # --- Table: stage accounting for the full system ------------------------
    stage_body = []
    for index, (family, stage_rows) in enumerate(
        (("LabTrend", lab_stage_values), ("MedDose", med_stages))
    ):
        for position, model in enumerate(models):
            row = stage_rows[model]
            prefix = (
                f"\\multirow{{{len(models)}}}{{*}}{{{family}}}" if position == 0 else ""
            )
            stage_body.append(
                f"{prefix} & {model} & "
                f"{pct(row['initial_joint_valid'])} & "
                f"{pct(row['post_repair_joint_valid'])} & "
                f"{pct(row['final_joint_valid'])} & "
                f"{pct(row['repair_rate'])} & "
                f"{pct(row['deterministic_fallback_rate'])} \\\\"
            )
        if index == 0:
            stage_body.append("\\midrule")
    stage_lines = table(
        "ll rrrrr",
        "Family & Checkpoint & Initial & +Repair & Final & Repair & Fallback \\\\",
        stage_body,
    )

    # --- Supplement: full per-system tables ---------------------------------
    def full_table(rows, cases, order, case_field) -> list[str]:
        body = []
        for position, model in enumerate(models):
            for offset, (system, label) in enumerate(order):
                row = rows[(model, system)]
                case = cases[(model, system)]
                model_cell = (
                    f"\\multirow{{{len(order)}}}{{*}}{{{model}}}" if offset == 0 else ""
                )
                joint = pct(row["joint_valid"])
                if system == "clinehr_os":
                    joint = f"\\textbf{{{joint}}}"
                body.append(
                    f"{model_cell} & {label} & {joint} & "
                    f"{pct(row['joint_valid_ci_low'])}--{pct(row['joint_valid_ci_high'])} & "
                    f"{pct(row['evidence_recall'])} & "
                    f"{pct(row['scope_violation'])} & "
                    f"{pct(row['overrestriction'])} & "
                    f"{pct(case[case_field])} \\\\"
                )
            if position != len(models) - 1:
                body.append("\\midrule")
        return table(
            "ll rrrrrr",
            "Checkpoint & System & Joint & Cluster 95\\% CI & Ev.R & SVR & "
            "Over-rest. & Both-task case \\\\",
            body,
        )

    lab_full_lines = full_table(lab, lab_cases, LAB_SYSTEM_ORDER, lab_case_field)
    med_full_lines = full_table(med, med_cases, MED_SYSTEM_ORDER, med_case_field)

    # --- Prose macros -------------------------------------------------------
    def span(rows, system, key) -> tuple[float, float]:
        values = [float(rows[(model, system)][key]) for model in models]
        return min(values), max(values)

    macro_lines = [
        HEADER,
        "% Compact macros for prose. Text macros end with \\xspace so that a",
        "% following space is not swallowed; math macros must not.",
    ]

    def emit(name: str, value: str, *, math: bool = False) -> None:
        body = value if math else f"{value}\\xspace"
        macro_lines.append(f"\\newcommand{{\\{name}}}{{{body}}}")

    def emit_range(name: str, low: float, high: float, suffix: str = "\\%") -> None:
        """Emit one macro holding a range, collapsed when the endpoints agree."""
        if pct(low) == pct(high):
            emit(name, f"{pct(low)}{suffix}")
        else:
            emit(name, f"{pct(low)}--{pct(high)}{suffix}")

    emit("NModels", str(len(models)))
    emit("NRuns", str(2 * len(models)))
    trajectories = len(models) * 128 * (len(LAB_SYSTEM_ORDER) + len(MED_SYSTEM_ORDER))
    emit("NTrajectories", f"{trajectories:,}")
    for family_tag, rows, cases, all_six, field in (
        ("Lab", lab, lab_cases, LAB_ALL_SIX, lab_case_field),
        ("Med", med, med_cases, MED_ALL_SIX, med_case_field),
    ):
        for system_tag, system in (
            ("AllSix", all_six),
            ("Scope", "scope_first"),
            ("Guard", "guard_refill"),
        ):
            low, high = span(rows, system, "joint_valid")
            emit(f"{family_tag}{system_tag}Min", f"{pct(low)}\\%")
            emit(f"{family_tag}{system_tag}Max", f"{pct(high)}\\%")
            emit_range(f"{family_tag}{system_tag}Range", low, high)
            low, high = span(cases, system, field)
            emit(f"{family_tag}{system_tag}CaseMin", f"{pct(low)}\\%")
            emit(f"{family_tag}{system_tag}CaseMax", f"{pct(high)}\\%")
            emit_range(f"{family_tag}{system_tag}CaseRange", low, high)
            low, high = span(rows, system, "evidence_recall")
            emit_range(f"{family_tag}{system_tag}EvR", low, high)
        low, high = span(rows, "late_no_refill", "overrestriction")
        emit_range(f"{family_tag}LateOverRange", low, high)
        # Largest and smallest scope-first minus all-six task-level gain.
        gains = [
            float(rows[(model, "scope_first")]["joint_valid"])
            - float(rows[(model, all_six)]["joint_valid"])
            for model in models
        ]
        emit(f"{family_tag}ScopeGainMin", f"{pct(min(gains))}")
        emit(f"{family_tag}ScopeGainMax", f"{pct(max(gains))}")

    # Matched general/medical pair, when both members are present.
    for family_tag, rows, all_six in (("Lab", lab, LAB_ALL_SIX), ("Med", med, MED_ALL_SIX)):
        for model in ("Gemma-3-27B", "MedGemma-27B"):
            if (model, "scope_first") not in rows:
                continue
            alias = MACRO_ALIAS[model]
            emit(f"{family_tag}{alias}AllSix", f"{pct(rows[(model, all_six)]['joint_valid'])}\\%")
            emit(
                f"{family_tag}{alias}Scope",
                f"{pct(rows[(model, 'scope_first')]['joint_valid'])}\\%",
            )
            emit(
                f"{family_tag}{alias}Guard",
                f"{pct(rows[(model, 'guard_refill')]['joint_valid'])}\\%",
            )
            emit(
                f"{family_tag}{alias}ScopeOverRest",
                f"{pct(rows[(model, 'scope_first')]['overrestriction'])}\\%",
            )

    # How often executing scope before retrieval beat information-complete
    # prompting. The manuscript states this is not universal, so the count and
    # the exception are both machine-generated rather than asserted in prose.
    scope_wins = 0
    scope_exceptions: list[str] = []
    for family_tag, rows, all_six in (("LabTrend", lab, LAB_ALL_SIX), ("MedDose", med, MED_ALL_SIX)):
        for model in models:
            gain = float(rows[(model, "scope_first")]["joint_valid"]) - float(
                rows[(model, all_six)]["joint_valid"]
            )
            if gain > 0:
                scope_wins += 1
            else:
                scope_exceptions.append(f"{model} on {family_tag}")
    emit("ScopeWinRuns", str(scope_wins))
    emit("ScopeExceptions", ", ".join(scope_exceptions) if scope_exceptions else "none")

    # Guard-refill minus all-six, the ordering that does hold everywhere.
    for family_tag, rows, all_six in (("Lab", lab, LAB_ALL_SIX), ("Med", med, MED_ALL_SIX)):
        gains = [
            float(rows[(model, "guard_refill")]["joint_valid"])
            - float(rows[(model, all_six)]["joint_valid"])
            for model in models
        ]
        emit(f"{family_tag}GuardGainMin", f"{pct(min(gains))}")
        emit(f"{family_tag}GuardGainMax", f"{pct(max(gains))}")

    # Per-checkpoint MedDose confirmatory p-values against the all-six baseline.
    for model in models:
        alias = MACRO_ALIAS[model]
        emit(
            f"Med{alias}FullAllP",
            tex_p(med_comparisons[(model, "clinehr_os", MED_ALL_SIX)]["holm_adjusted_case_p"]),
            math=True,
        )
        emit(
            f"Med{alias}FullScopeP",
            tex_p(med_comparisons[(model, "clinehr_os", "scope_first")]["holm_adjusted_case_p"]),
            math=True,
        )

    # Largest MedDose confirmatory p-value in the panel, for a one-sentence claim.
    worst_all = max(
        float(med_comparisons[(model, "clinehr_os", MED_ALL_SIX)]["holm_adjusted_case_p"])
        for model in models
    )
    worst_scope = max(
        float(med_comparisons[(model, "clinehr_os", "scope_first")]["holm_adjusted_case_p"])
        for model in models
    )
    emit("MedWorstFullAllP", tex_p(worst_all), math=True)
    emit("MedWorstFullScopeP", tex_p(worst_scope), math=True)

    # Share of single generations that hit the shared token budget. Reported so
    # that a verbose checkpoint is not silently penalized by a shared setting.
    for family_tag, rates in truncation.items():
        if rates:
            emit(f"{family_tag}TruncMax", f"{pct(max(rates.values()))}\\%")

    # Intervention rates across the panel.
    for family_tag, stage_rows in (("Lab", lab_stage_values), ("Med", med_stages)):
        for key, tag in (
            ("initial_joint_valid", "Initial"),
            ("repair_rate", "Repair"),
            ("deterministic_fallback_rate", "Fallback"),
        ):
            values = [float(stage_rows[model][key]) for model in models]
            emit(f"{family_tag}{tag}Min", f"{pct(min(values))}\\%")
            emit(f"{family_tag}{tag}Max", f"{pct(max(values))}\\%")
            emit_range(f"{family_tag}{tag}Range", min(values), max(values))
    macro_lines.append("")

    args.output_dir.mkdir(parents=True, exist_ok=True)
    outputs = {
        args.output_dir / "main_results_table.tex": main_lines,
        args.output_dir / "combined_results_table.tex": combined_lines,
        args.output_dir / "case_results_table.tex": case_lines,
        args.output_dir / "stage_results_table.tex": stage_lines,
        args.output_dir / "lab_full_results_table.tex": lab_full_lines,
        args.output_dir / "med_full_results_table.tex": med_full_lines,
        args.output_dir / "result_macros.tex": macro_lines,
    }
    for path, content in outputs.items():
        path.write_text("\n".join(content), encoding="utf-8")
        print(path)


if __name__ == "__main__":
    main()
